def _json_values():
    """Any value a signed field may hold: recursive but bounded, and deliberately
    adversarial -- None, booleans, integers across the 64-bit boundaries, unicode that
    forces JSON escaping, and nested lists/dicts whose element and key order is a drift
    trap. No floats: the real statements carry none, and they would only add NaN/Infinity
    noise that both sides serialize identically anyway."""
    scalar = st.one_of(
        st.none(),
        st.booleans(),
        st.integers(min_value=-(2 ** 63), max_value=2 ** 64),
        st.text(st.characters(min_codepoint=1, max_codepoint=0x10FFFF,
                              blacklist_categories=("Cs",)), max_size=40),
    )
    return st.recursive(
        scalar,
        lambda children: st.one_of(
            st.lists(children, max_size=4),
            st.dictionaries(st.text(min_size=1, max_size=8), children, max_size=4),
        ),
        max_leaves=8,
    )


def _bodies_for(spec):
    """A body mapping each signed key to a generated value, with the app-controlled
    constants pinned. Keys are always present (present-with-null is distinct from absent,
    and every builder reads with .get())."""
    fixed = spec.get("fixed", {})
    mapping = {k: (st.just(fixed[k]) if k in fixed else _json_values()) for k in spec["keys"]}
    return st.fixed_dictionaries(mapping)


_SETTINGS = settings(max_examples=250, deadline=None,
                     suppress_health_check=[HealthCheck.too_slow])


def _slug(name):
    return name.replace("-", "_")


def _make_methods(name, spec):
    app_fn, ver_fn, keys = spec["app"], spec["verify"], spec["keys"]
    bodies = _bodies_for(spec)

    @given(body=bodies)
    @_SETTINGS
    def cross_impl_equivalence(self, body):
        self.assertEqual(app_fn(body), ver_fn(body),
                         "%s: the app signer and the offline verifier disagree on the canonical bytes" % name)

    @given(body=bodies)
    @_SETTINGS
    def deterministic(self, body):
        self.assertEqual(app_fn(body), app_fn(dict(body)))
        self.assertEqual(ver_fn(body), ver_fn(dict(body)))

    @given(body=bodies, data=st.data())
    @_SETTINGS
    def key_order_invariant(self, body, data):
        shuffled = dict(data.draw(st.permutations(list(body.items()))))
        self.assertEqual(app_fn(shuffled), app_fn(body),
                         "%s: the app's signed bytes depend on input key order (not sorted?)" % name)
        self.assertEqual(ver_fn(shuffled), ver_fn(body),
                         "%s: the verifier's canonical bytes depend on input key order" % name)

    @given(body=bodies,
           extra=st.dictionaries(
               st.text(min_size=1, max_size=12).filter(lambda k: k not in keys),
               _json_values(), max_size=4))
    @_SETTINGS
    def signature_envelope_excluded(self, body, extra):
        # The signature envelope, and any other stray key, must never change the signed
        # bytes -- otherwise the signature would sign (part of) itself.
        extra.setdefault("signature_hex", "deadbeef")
        extra.setdefault("public_key_hex", "cafe")
        polluted = dict(body)
        polluted.update(extra)
        self.assertEqual(app_fn(polluted), app_fn(body),
                         "%s: an extra key changed the app's signed bytes (envelope leak)" % name)
        self.assertEqual(ver_fn(polluted), ver_fn(body),
                         "%s: an extra key changed the verifier's canonical bytes" % name)

    @given(body=bodies)
    @_SETTINGS
    def json_roundtrip_stable(self, body):
        reparsed = json.loads(json.dumps(body))
        self.assertEqual(app_fn(reparsed), app_fn(body))
        self.assertEqual(ver_fn(reparsed), ver_fn(body))

    @given(body=bodies)
    @_SETTINGS
    def canonical_form(self, body):
        out = app_fn(body)
        self.assertIsInstance(out, bytes)
        # The output is exactly the compact, sorted-key canonicalization of its own
        # content: re-serializing the parsed output under the canonical settings
        # reproduces it byte for byte. This catches a non-compact separator or an
        # unsorted key without mistaking a VALUE that merely contains ", " for a
        # separator (a naive substring check would; Hypothesis found that at once).
        parsed = json.loads(out)
        recanon = json.dumps(parsed, sort_keys=True, separators=(",", ":")).encode("utf-8")
        self.assertEqual(out, recanon,
                         "%s: output is not the compact, sorted-key canonical form" % name)
        self.assertEqual(list(parsed.keys()), sorted(parsed.keys()),
                         "%s: top-level keys are not in sorted order" % name)

    s = _slug(name)
    return {
        "test_%s_cross_impl_equivalence" % s: cross_impl_equivalence,
        "test_%s_deterministic" % s: deterministic,
        "test_%s_key_order_invariant" % s: key_order_invariant,
        "test_%s_signature_envelope_excluded" % s: signature_envelope_excluded,
        "test_%s_json_roundtrip_stable" % s: json_roundtrip_stable,
        "test_%s_canonical_form" % s: canonical_form,
    }


# One TestCase per signed type, each carrying the six metamorphic properties. Built inside
# a function so the loop variables never leak into the module namespace, where unittest
# would discover a stray name as a second alias for the last class and run its cases twice.
def _install_oracle_classes():
    for name, spec in SIGNED_TYPES.items():
        cls = type("CanonicalOracle_%s" % _slug(name), (unittest.TestCase,), _make_methods(name, spec))
        globals()[cls.__name__] = cls


_install_oracle_classes()


class CanonicalEquivalenceCoverage(unittest.TestCase):
    """The oracle must cover every signed type that exists, so a sixth type added later
    without an oracle case fails here rather than sailing through unverified."""

    def test_covers_every_signed_format_in_the_verifier(self):
        with open(os.path.join(_ROOT, "scripts", "polaris-verify.py")) as f:
            verify_src = f.read()
        # Every `polaris-*/1` format literal the verifier knows must have an oracle case,
        # except formats with no app-side statement builder to differentially test here:
        # the authenticity pack (SHA3-256(token_value), no canonical-JSON builder; covered by
        # the vectors and every drill), the witness cosignature (signed by an independent
        # witness, not the app; agreement proven by the gossip drill), and the publication
        # receipt (a bundle whose only signed part is the LEDGER's own STH -- itself the
        # transparency-sth type, already covered -- with the rest an inclusion proof;
        # agreement proven by the publication drill).
        import re
        formats = set(re.findall(r'"(polaris-[a-z-]+/1)"', verify_src))
        covered = {
            "polaris-federation-manifest/1", "polaris-epoch-checkpoint/1",
            "polaris-revocation-feed/1", "polaris-status-assertion/1",
            "polaris-transparency-sth/1", "polaris-federation-status-bundle/1",
            "polaris-exchange-receipt/1", "polaris-exchange-mint/1", "polaris-timestamp/1",
            "polaris-registry/1", "polaris-exchange-request/1",
            "polaris-signed-document/1", "polaris-id-token/1",
            "polaris-trust-list/1", "polaris-trust-attestation/1",
            "polaris-holder-binding/1", "polaris-holder-proof/1", "polaris-epoch-leaves/1",
            # P9.8: delegation. Signed by the holder's key and the agent's, not the issuer's,
            # but the app builds the identical bytes to VERIFY one, so the oracle covers them.
            "polaris-agent-grant/1", "polaris-grant-revocation/1", "polaris-agent-proof/1",
        }
        not_app_signed = {"polaris-authenticity-pack/1", "polaris-transparency-cosignature/1",
                          "polaris-transparency-publication/1", "polaris-published-head/1",
                          # P8.6: the holder-side wrapper and its QR framing carry no app signature
                          "polaris-presentation/1", "polaris-qr/1",
                          # P9.4: a domain-separation TAG inside a SHA3-256 preimage, not a
                          # signed artifact. It matches the format-string shape on purpose, so
                          # that a handle cannot be confused with another value in the protocol,
                          # and it is named here rather than reshaped to dodge this scan.
                          "polaris-pairwise/1"}
        missing = formats - covered - not_app_signed
        self.assertFalse(missing, "signed formats with no canonical-equivalence oracle case: %s" % missing)


if __name__ == "__main__":
    unittest.main()
