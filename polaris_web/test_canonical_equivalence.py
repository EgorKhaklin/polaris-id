"""
test_canonical_equivalence.py — the canonical-signing equivalence oracle.

Polaris has five signed statement types. Each is signed by the application over a
canonical byte string, and verified OFFLINE by scripts/polaris-verify.py, which
reconstructs that same byte string independently. If the two sides ever disagree on a
single byte -- a key added on one side, a separator changed, a sort dropped -- the
application keeps signing happily while EVERY offline verification fails, silently.
That is the subtlest and highest-impact failure mode in the system, and it is exactly
the kind a single worked example does not catch.

This is a differential + metamorphic oracle over the two canonicalizations. For each
signed type it treats the app-side builder and the verify-side builder as two
independent implementations of one spec and, over inputs generated by Hypothesis
(unicode that forces JSON escaping, key reorderings, nested structures, integer
boundaries, stray keys), asserts the properties that MUST hold:

  - cross-implementation equivalence: app(body) == verify(body), byte for byte;
  - determinism: a builder is a pure function of its input;
  - key-order invariance: the output does not depend on input key order (sorted keys);
  - signature-envelope exclusion: signature_hex / public_key_hex and any other extra key
    never enter the signed bytes (a security property -- the signature cannot sign itself);
  - JSON round-trip stability: serializing and reparsing the body does not perturb it;
  - canonical form: the output is compact (no ", " or ": ") and its keys are sorted.

It is deliberately crypto-free. Byte equality of the signed statement is what makes an
app signature verifiable offline, and it holds independent of the signing key, so the
oracle needs no liboqs and runs in the ordinary product-test job. The real ML-DSA-65
round-trip -- that a signature over app(body) verifies against SHA3-256(verify(body)) --
is proven per type by the pqc-real drills (the manifest, offline-status, epoch-revocation
and two-instance drills). check_canonical_equivalence pins this oracle and statically
compares the two sides' key lists.
"""
